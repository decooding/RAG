def format_single_chunk(idx: int, chunk: Union[SearchResult, Dict[str, Any]]) -> str:
    """Форматирует отдельный чанк для передачи в контекст LLM."""
    if isinstance(chunk, SearchResult):
        art_num = chunk.article_number or "Без номера"
        art_title = chunk.article_title or ""
        source = chunk.metadata.get("source", "")
        text = chunk.text
    else:
        art_num = chunk.get("article_number", chunk.get("metadata", {}).get("article_number", "Без номера"))
        art_title = chunk.get("article_title", chunk.get("metadata", {}).get("article_title", ""))
        source = chunk.get("metadata", {}).get("source", "")
        text = chunk.get("text", "")

    header = f"--- [ФРАГМЕНТ #{idx} | Статья {art_num}"
    if art_title:
        header += f": {art_title}"
    if source:
        header += f" | Источник: {source}"
    header += "] ---"

    return f"{header}\n{text}\n"


def build_user_prompt(query: str, search_results: List[Union[SearchResult, Dict[str, Any]]]) -> str:
    """
    Формирует финальный текст запроса к LLM с инкапсулированным контекстом.
    """
    if not search_results:
        context_str = "[Внимание: Релевантные статьи не найдены в базе данных]\n"
    else:
        formatted_chunks = [
            format_single_chunk(i, chunk)
            for i, chunk in enumerate(search_results, start=1)
        ]
        context_str = "\n".join(formatted_chunks)

    prompt = f"""КОНТЕКСТ (СТАТЬИ НПА РК):
==================================================
{context_str}==================================================

ВОПРОС ПОЛЬЗОВАТЕЛЯ:
{query.strip()}

СФОРМИРУЙ ЮРИДИЧЕСКИЙ ОТВЕТ В СТРОГОМ СООТВЕТСТВИИ С РЕГЛАМЕНТОМ:"""
    return prompt
